    reload: ['..####.#', '.#....##', '#....###', '#.......', '#.......', '#......#', '.#....#.', '..####..'],
    rotate: ['#.####..', '##....#.', '###....#', '.......#', '.......#', '#......#', '.#....#.', '..####..'],
    sync: ['.#....#.', '###...#.', '.#....#.', '.#....#.', '.#....#.', '.#...###', '.#....#.', '........'],
    phone: ['.######.', '.#....#.', '.#....#.', '.#....#.', '.#....#.', '.#....#.', '.##..##.', '.######.'],
    screen: ['########', '#......#', '#.####.#', '#.####.#', '#.####.#', '#.####.#', '#......#', '########'],
    down: ['...##...', '...##...', '...##...', '...##...', '########', '.######.', '..####..', '...##...'],
